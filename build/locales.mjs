/**
 * 从 `locale/*.json` 生成客户端字典。
 *
 * 语言文件是唯一事实来源：`meta` 供宿主读插件显示名，`ui` 是界面文案。生成物
 * 入库并在 `npm run check` 里比对最新，避免打包/发布时依赖一个额外的构建步骤；
 * 也让人能在 diff 里直接看到字典变化。
 *
 * 用法：
 *   node build/locales.mjs          # 重写 src/client/locales.generated.js
 *   node build/locales.mjs --check  # 只校验生成物是否最新（过期退出 1）
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
export const LOCALE_DIR = join(root, 'locale')
export const GENERATED_FILE = join(root, 'src/client/locales.generated.js')

/** 语言文件名必须同时是宿主识别的 BCP 47 风格 id。 */
const LANGUAGE_ID = /^[a-z]{2,8}(?:-[a-z0-9]{1,8})*$/

/**
 * 读入并校验全部语言文件。
 *
 * @returns {{ code: string, meta: { title: string, description: string }, ui: Record<string, string> }[]}
 *   按语言码排序的语言文件
 */
export function readLocales() {
  const files = readdirSync(LOCALE_DIR, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith('.json'))
    .map((entry) => entry.name)
    .sort()
  if (files.length === 0) throw new Error('locale/: 至少需要一个语言文件')
  const locales = files.map((file) => {
    const code = file.slice(0, -5)
    if (!LANGUAGE_ID.test(code)) throw new Error(`locale/${file}: 文件名必须是语言 id`)
    const parsed = JSON.parse(readFileSync(join(LOCALE_DIR, file), 'utf8'))
    if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) {
      throw new Error(`locale/${file}: 顶层必须是对象`)
    }
    const meta = parsed.meta
    if (typeof meta !== 'object' || meta === null || Array.isArray(meta)) {
      throw new Error(`locale/${file}: meta 必须是对象`)
    }
    if (typeof meta.title !== 'string' || meta.title.trim() === '') {
      throw new Error(`locale/${file}: meta.title 必须是非空字符串`)
    }
    if (typeof meta.description !== 'string' || meta.description.trim() === '') {
      throw new Error(`locale/${file}: meta.description 必须是非空字符串`)
    }
    const ui = parsed.ui
    if (typeof ui !== 'object' || ui === null || Array.isArray(ui)) {
      throw new Error(`locale/${file}: ui 必须是对象`)
    }
    for (const [key, value] of Object.entries(ui)) {
      if (typeof value !== 'string' || value.trim() === '') {
        throw new Error(`locale/${file}: ui.${key} 必须是非空字符串`)
      }
    }
    return { code, meta: { title: meta.title, description: meta.description }, ui }
  })
  if (!locales.some((locale) => locale.code === 'en')) {
    throw new Error('locale/: 缺少 en（宿主缺 key 时回退英文）')
  }
  return locales
}

/**
 * 把语言文件渲染成客户端模块。
 *
 * @param {{ code: string, ui: Record<string, string> }[]} locales - 语言文件
 * @returns {string} 模块源码
 */
export function renderLocales(locales) {
  const lines = [
    '// Generated by build/locales.mjs from locale/*.json. Do not edit by hand.',
    '',
    'export const LOCALE_UI = Object.freeze({',
  ]
  for (const { code, ui } of locales) {
    lines.push(`  ${JSON.stringify(code)}: Object.freeze({`)
    for (const key of Object.keys(ui).sort()) {
      lines.push(`    ${JSON.stringify(key)}: ${JSON.stringify(ui[key])},`)
    }
    lines.push('  }),')
  }
  lines.push('})', '')
  return lines.join('\n')
}

/**
 * 生成或校验客户端字典。
 *
 * @param {{ check?: boolean }} [options] - `check` 只校验不写盘
 * @returns {boolean} `check` 为真时返回是否最新
 */
export function generate({ check = false } = {}) {
  const source = renderLocales(readLocales())
  if (check) {
    let current = ''
    try {
      current = readFileSync(GENERATED_FILE, 'utf8')
    } catch {
      return false
    }
    return current === source
  }
  writeFileSync(GENERATED_FILE, source)
  return true
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check')
  if (check && !generate({ check: true })) {
    console.error('错误: src/client/locales.generated.js 不是最新；运行 node build/locales.mjs')
    process.exit(1)
  }
  if (!check) generate()
}
